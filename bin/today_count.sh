#!/bin/bash
# 오늘 이미 나간 영상·카드 편수를 센다 (2026-08-30 신설).
# 결번 판단에 쓴다 — 영상이 하루 3편 체제가 되면서 결번 1건의 비용이 2배가 됐다.
cd "$(dirname "$0")/.." || exit 1
D=$(date +%F)
# IG:xxx.mp4(인스타 게시 기록)를 함께 세면 편수가 2배가 된다 (2026-09-02 실사고:
# 유튜브 4편인데 8편으로 세어 결번 판정이 느슨해졌다). 유튜브 게시분만 센다.
V=$(grep "^${D}" logs/sent.log 2>/dev/null | grep -v 'IG:' | grep -c '\.mp4$')
C=$(grep "^${D}" logs/sent.log 2>/dev/null | grep -cE 'IGCARD:|THCARD:')
H=$(date +%H)
echo "오늘(${D}) 게시: 영상 ${V}/3편 · 카드 ${C}/5장 (현재 ${H}시)"
if [ "$V" -eq 0 ] && [ "$H" -ge 20 ]; then
  echo "⛔ 마지막 영상 슬롯인데 오늘 영상 0편 — **결번 금지**. 게이트를 통과하는 최선의 후보로 반드시 내보내라."
elif [ "$V" -eq 0 ]; then
  echo "⚠️ 오늘 아직 영상 0편 — 결번을 고르기 전에 기준을 한 번 더 재봐라(3편 체제라 결번 1건의 비용이 크다)."
else
  echo "✅ 오늘 영상 ${V}편 게시됨 — 통상 기준으로 판단해도 된다."
fi
