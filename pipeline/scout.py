import json
import os
import sys
import time
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODEL = "gemini-2.5-flash"
URL = "https://generativelanguage.googleapis.com/v1beta/models/%s:generateContent?key=%s"


def _key():
    for line in open(os.path.join(ROOT, "keys.env"), encoding="utf-8"):
        line = line.strip()
        if line.startswith("GEMINI_API_KEY="):
            return line.split("=", 1)[1].strip().strip('"')
    raise RuntimeError("keys.env에 GEMINI_API_KEY가 없다")


PROMPT = """## ⏱ 지금은 %s (한국시간)입니다. 이 시각이 절대 기준입니다.

당신은 한국의 지식 숏폼 채널 '1일 1지식'의 소재 스카우트입니다.
구글 검색으로 **지금 이 시각 한국에서 실제로 벌어지고 있는 일**을 찾아
오늘 올릴 40~55초 지식 영상의 소재 후보를 뽑아주세요.

## 🚨 시점 규칙 — 어기면 결과물 전체가 무효입니다
- **당신의 학습 데이터에 있는 과거 정보를 절대 쓰지 마세요.** 반드시 지금 구글 검색을 실행해서 나온 것만 쓰세요.
- **24시간 이내에 발생하거나 보도된 것**만 후보로 올리세요. 며칠 지난 뉴스는 이미 다른 채널이 다 다뤘습니다.
- 예정된 이벤트는 예외지만, **오늘부터 7일 이내**에 일어나는 것만 됩니다.
- 각 후보에 **정보 시각**(발생·보도 시각)을 반드시 적으세요. 시각을 모르면 그 후보는 버리세요.
- 계절·날씨·시세처럼 시간이 지나면 틀려지는 정보는 **오늘 자 실측치**로 확인하세요.
  (예: "지금 폭염" 같은 표현을 쓰기 전에 오늘 기상 특보를 검색해서 확인)

## 반드시 검색해서 확인할 것
1. 오늘의 기상 상황 — 특보(호우·태풍·폭염·건조·강풍), 지진, 이상현상
2. 실시간 검색어·포털 랭킹뉴스에서 지금 사람들이 뭘 보고 있는지
3. 커뮤니티(디시·에펨·네이트판·더쿠)에서 지금 도는 밈이나 화제
4. 오늘~이번 주 예정된 이벤트(천문현상, 개봉, 공개, 제도 시행, 마감)

## 좋은 소재의 조건 (실측으로 검증된 공식 — 5개 중 3개 이상 충족해야 함)
1. **오늘/오늘 밤이어야 하는가** — 내일 보면 늦는가
2. **누구나 할 수 있는가** — 돈·장비·전문지식이 필요하면 공유되지 않는다
3. **같이 할 사람이 떠오르는가** — "우리 나가볼까?"의 대상이 있는가
4. **놓치면 아쉬운가** — 손실 회피가 공유를 만든다
5. **연령을 가리지 않는가** — 10대도 60대도 반응하는가

실측: 이 조건을 채운 편은 30만·16만·7.5만 조회가 나왔고, 못 채운 편은 200회에서 끝났습니다.

## 🌦 현재 조건과 반드시 교차 검증하세요 (실사고 기반)
소재 하나하나를 **오늘의 실제 상황**에 대보세요. 조건이 안 맞으면 아무리 시의성이 있어도 버립니다.
- **하늘·야외 소재(유성우·달·별·노을·산책)** → 오늘 밤 **구름·비 예보**를 먼저 검색하세요.
  실사고: 2026-08-17 전국에 비가 오는 날 유성우를 후보로 올렸습니다. 하늘이 안 보이는데 무의미합니다.
- **야외 활동·나들이 소재** → 강수·기온·특보 확인
- **요일·시간대** → 오늘이 휴일인지 평일인지, 사람들이 지금 무엇을 하는 시간인지
  (예: 연휴 마지막 날이면 '내일 출근·개학' 감정이 전 국민 공통이다)
- 각 후보에 **'현재 조건 확인'** 한 줄을 넣어, 무엇을 대조했는지 밝히세요.
- **지역 범위**: 소재는 **전 지역이 함께 겪거나 볼 수 있는 것**이 기본입니다. 특정 지역만 다루는 소재는 **그곳에 이상현상이 났을 때만** 올리세요(지진·이상기온·기현상). 한 지역 얘기는 나머지 시청자 전부를 배제합니다.

## 🚫 과장 금지 (실사고 기반)
- **"쏟아진다·역대급·엄청난" 같은 강도 표현을 쓰지 마세요.** 실제 수치를 찾아 그대로 쓰세요.
  실사고: 2026-08-17 백조자리 카파 유성우를 "쏟아집니다"로 제안했으나, 실제 ZHR은 **시간당 3개**로
  페르세우스(100개)의 1/30이었습니다. 그대로 냈으면 허위가 됩니다.
- 수치를 못 찾으면 그 후보의 '검증 필요'에 **"규모 수치 미확인"**이라고 명시하세요.
- 오히려 **수치가 작다는 사실 자체가 반전 소재**가 되는 경우가 많습니다
  (예: "시간당 3개뿐인데, 대신 하나가 크고 느리게 지나간다").

## 절대 제외
- 정치·정당·정치인·진영 (중립 원칙, 최상위 규약)
- 인명 피해가 있거나 원인이 미확정인 사고
- 특정 연령·성별만 겨냥한 소재 (예: 청소·빨래처럼 좁은 생활 소재)
- 확인되지 않은 수치나 블로그발 주장

## 출력 형식 (다른 말 없이 이것만)
각 후보를 아래처럼 5개 쓰세요. 반드시 서로 다른 분야에서 고르세요.

### 후보 N
- 소재:
- 정보 시각: (예: 2026-08-17 06:40 보도 / 8/18 20:00 예정 — 모르면 후보에서 제외)
- 훅 첫 줄: (한 문장으로 끝나야 함. 조건절 '~면/~아도'이나 명사구로 끝내지 말 것)
- 왜 오늘인가:
- 공식 충족: (1~5 중 몇 개, 어느 것)
- 근거 출처: (기관·매체명과 URL. 블로그 금지)
- 현재 조건 확인: (오늘 날씨·요일·시간대와 대조한 결과. 안 맞으면 후보에서 빼라)
- 검증 필요: (반드시 채울 것. '없음'은 금지 — 당신이 확신해도 우리는 원출처로 다시 확인한다. 특히 **수치·규모·강도**는 과장되기 쉬우니 무엇을 확인해야 하는지 지목하라)
%s"""


def scout(extra=""):
    key = _key()
    now = time.strftime("%Y년 %m월 %d일 %H시 %M분")
    body = {
        "contents": [{"parts": [{"text": PROMPT % (now, ("\n## 추가 지시\n" + extra) if extra else "")}]}],
        "tools": [{"google_search": {}}],
        "generationConfig": {"temperature": 0.9},
    }
    req = urllib.request.Request(URL % (MODEL, key),
                                 data=json.dumps(body).encode(), method="POST")
    req.add_header("Content-Type", "application/json")
    with urllib.request.urlopen(req, timeout=180) as r:
        d = json.load(r)
    parts = d["candidates"][0]["content"]["parts"]
    return "".join(p.get("text", "") for p in parts)


if __name__ == "__main__":
    print(scout(" ".join(sys.argv[1:])))
