# 조사 꼬리('없이·안에·주머니에')를 따로 거르는 규칙도 넣어봤지만 폐기했다 —
# 임계 3이면 그 조각들은 어차피 2개짜리라 걸리지 않는데, '경도·속도·강도'처럼 조사와 같은
# 소리로 끝나는 **진짜 낱말**을 죽여 보호필름 9H 경도 편이 중복인데 통과했다.
# 세 설정(임계만 / 임계+부류+조사 / 임계+부류)을 중복 판정 19건 전건에 돌려 고른 결과다.


def _is_weak(w):
    """소재를 특정하지 못하는 낱말인가."""
    return w.lower() in _CATEGORY


# 모델 표기는 제품명의 일부다 — 'S26'·'FE'·'11'·'Pro'가 겹쳤다고 같은 글이 아니다.
# (2026-08-28 오탐: '갤럭시 S26 FE 배터리 후기'가 'S26 FE 유출 정리'와 중복 판정됐다)
_MODEL = re.compile(r"^(?:[0-9]+|[A-Za-z]{1,3}[0-9]+[A-Za-z]*|[0-9]+[A-Za-z]+"
                    r"|FE|Pro|Plus|Ultra|Max|Air|Mini|Lite|SE)$", re.I)


def _is_model(w):
    return bool(_MODEL.match(w))


def is_dup(new_text, existing_titles, min_overlap=3):
    """(중복여부, 겹친 글 제목, 겹친 낱말). existing_titles는 이미 있는 글 제목 목록."""
    nk = _keys(new_text)
    if not nk:
        return False, None, []
    from product_match import BRANDS
    for t in existing_titles:
        ek = _keys(t)
        both = nk & ek
        if len(both) < min_overlap:
            continue
        # **제품명만 겹치는 것은 중복이 아니다.** 같은 기기의 다른 각도(픽셀11 알림등 vs
        # 픽셀11 카메라)는 별개 글이어야 한다. 브랜드·제품군·모델번호를 빼고도
        # 소재를 특정하는 낱말이 남아야 중복으로 본다 (2026-08-28 오탐 교정).
        core = [w for w in both
                if w.lower() not in BRANDS and not _is_model(w) and not _is_weak(w)]
        # 기존 글 쪽은 **제목만** 넘긴다 (2026-08-28 재감사 확정): 본문을 넣으면
        # '많습니다·경우가·고민하는' 같은 한국어 활용형이 우연히 겹쳐 무관한 글이 전부
        # 중복 판정됐다(샤오미 스피커↔젠하이저 이어폰 등 초안 대부분 오탐). 정체성 낱말은
        # 제목에 있고 잡담 낱말은 본문에 있다 — 새 글 쪽(probe)만 topic+caption으로 넓힌다.
        if len(core) >= min_overlap:
            return True, t, sorted(both)
    return False, None, []
