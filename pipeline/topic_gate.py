#!/usr/bin/env python3
"""영상 소재 게이트 — 생활정보·실용 소재를 제목 단계에서 기계로 막는다 (2026-09-28).

왜: 4주 80편 실측(8/31~9/25, 게시 3일+)에서 생활정보·실용 19편의 유튜브 조회 중앙값이
  413으로 다른 계열(1,010~1,373)의 40%였고, 9/18 이후 7편은 56·61·60·81·89·271·413이었다
  (추석 택배·독감·귀성길·전기요금·병원·통장). 철칙 2번과 음성 목록이 프롬프트에 있었는데도
  19편이 새어 나갔다 — 세션은 매번 "반전이 있다"로 자기설득했다. 문구로는 안 막힌다.
예외 하나: 날짜가 박힌 행동 경고형. 「추석 KTX 예매 내일부터 — 지금 확인하세요」는
  같은 계열인데 2,927로 4주 최고였다. 차이는 '내일'과 '확인하세요' — 해설이 아니라 경보다.
판정은 **제목**으로 한다. 시청자가 피드에서 보는 것이 제목·첫 자막이고, 계열 태그는
  세션이 붙이는 것이라 얼마든지 바꿔 달 수 있다.
"""
import re

# 개인이 혼자 겪는 생활 사무 — 이 낱말이 제목의 중심이면 생활정보 소재다
LIFE = ("택배", "고지서", "요금", "병원", "약국", "응급실", "귀성", "귀경", "고속도로", "통행료",
        "통장", "자동이체", "카드값", "독감", "감기", "벌초", "장보기", "차례상 비용",
        "환급", "지원금", "보험료", "연말정산", "청약", "주차", "택시비", "휴게소",
        "명절 증후군", "연휴에", "연휴 끝", "연휴 화재", "콘센트", "냉장고 정리", "음식물")
# 날짜가 박힌 행동 경고 — 예외로 통과시킨다
TIMING = re.compile(r"오늘|내일|모레|이번 주|\d+일(부터|까지|마감)|D-?\d+|마감|마지막(입니다| 날)")
ACTION = re.compile(r"확인하세요|확인해 ?보세요|하세요|챙기세요|신청하세요|바꾸세요|지금")


def judge(title, override=None):
    """(통과, 사유). override: 중대 속보(서열 ②)로 이 게이트를 넘길 때 적는 사유 — 10자 이상."""
    if override and len(str(override).strip()) >= 10:
        return True, "게이트 우회(중대 속보): %s" % str(override).strip()[:80]
    t = str(title or "")
    hit = [w for w in LIFE if w in t]
    if not hit:
        return True, "생활정보 신호 없음"
    if TIMING.search(t) and ACTION.search(t):
        return True, "생활정보지만 날짜+행동 경고형(예외) — %s" % ", ".join(hit[:3])
    return False, ("생활정보·실용 소재(%s) — 4주 실측 중앙 413회, 9/18 이후 7편 평균 147회. "
                   "예외는 제목에 날짜(오늘·내일·N일까지)와 행동 지시(확인하세요·지금)가 "
                   "둘 다 있는 경고형뿐이다. 다른 소재를 골라라." % ", ".join(hit[:3]))


if __name__ == "__main__":
    import sys
    ok, why = judge(" ".join(sys.argv[1:]))
    print(("✅ " if ok else "⛔ ") + why)
    sys.exit(0 if ok else 1)
