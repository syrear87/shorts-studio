#!/usr/bin/env python3
"""AI 상투구 제거 — 생성 직후 자동 적용 (2026-08-27 신설).

디렉터: "너무너무너무 AI 티난다". 이모지는 프롬프트로 막았지만, 실측해 보니 표현 쪽은
  프롬프트만으로 안 막혔다. 생성된 65편을 전수 검사한 결과:
    '다양한' 51편 · '것이 좋습니다' 40편 · '더욱' 36편 · '따라서' 15편
    '살펴보겠습니다' 9편 · '필수적입니다' 7편 · '현명한 선택' 6편
  — 즉 **65편 전부**에 하나 이상 들어 있었다. 모델은 지시해도 이 습관을 되풀이한다.

왜 재생성이 아니라 치환인가: 글을 다시 쓰게 하면 수치와 출처가 함께 바뀔 위험이 있다.
  블로그 글은 검색에 영구히 남아 팩트 사고의 대가가 크다. 표현 단위만 손대고
  사실 관계는 건드리지 않는다.

태그 바깥 텍스트만 치환한다 — style·href 속성값에 치환이 들어가면 레이아웃이 깨진다.
"""
import re

RULES = [
    # 진행 안내형 — 블로그 글에 강연 말투는 필요 없다
    (r"살펴보겠습니다", "정리했습니다"),
    (r"알아보겠습니다", "정리했습니다"),
    (r"정리해 ?보겠습니다", "정리했습니다"),
    (r"소개해 ?드리겠습니다", "정리했습니다"),
    (r"마무리하겠습니다", "정리합니다"),
    (r"~에 대해 알아", "에 대해 정리했"),
    # 과장·상투 수식
    (r"현명한 선택을 (하시기 바랍니다|하실 수 있습니다)", "판단하시면 됩니다"),
    (r"현명한 선택", "판단"),
    (r"매우 중요합니다", "중요합니다"),
    (r"필수적입니다", "꼭 필요합니다"),
    (r"필수적으로 ", ""),
    # 문장 머리 접속 부사 — 없어도 뜻이 그대로다
    (r"(^|[.!?]\s|>)\s*결론적으로,?\s*", r"\1"),
    (r"(^|[.!?]\s|>)\s*무엇보다,?\s*", r"\1"),
    (r"(^|[.!?]\s|>)\s*이처럼,?\s*", r"\1"),
    (r"(^|[.!?]\s|>)\s*과연\s+", r"\1"),
    (r"(^|[.!?]\s|>)\s*따라서,?\s*", r"\1"),
    # 부사 남용
    (r"더욱더\s*", "훨씬 "),
    (r"더욱\s+", ""),
    (r"다양한\s+", ""),
    # 권유형 어미
    (r"확인하는 것이 좋습니다", "확인하세요"),
    (r"두는 것이 좋습니다", "두세요"),
    (r"보는 것이 좋습니다", "보세요"),
    (r"하는 것이 좋습니다", "하세요"),
    (r"것이 좋습니다", "쪽이 낫습니다"),
    (r"하시기 바랍니다", "주세요"),
]


def clean(html):
    """HTML에서 태그 바깥 텍스트의 상투구만 치환한다."""
    if not html:
        return html
    parts = re.split(r"(<[^>]+>)", html)
    for i in range(0, len(parts), 2):       # 짝수 인덱스 = 태그 바깥 텍스트
        t = parts[i]
        for pat, rep in RULES:
            t = re.sub(pat, rep, t)
        parts[i] = re.sub(r"  +", " ", t)
    return "".join(parts)


def clean_text(s):
    """제목처럼 태그가 없는 문자열용."""
    if not s:
        return s
    for pat, rep in RULES:
        s = re.sub(pat, rep, s)
    return re.sub(r"  +", " ", s).strip()
